/**
 * Returns SVG markup with customizable attributes
 * @param {keyof typeof icons} name - Icon identifier
 * @param {object} [options] - Options (className, size, strokeWidth)
 * @returns {string} SVG HTML string
 */
export function renderIcon(name, { className = '', size, strokeWidth } = {}) {
  let svg = icons[name] || '';
  if (!svg) return '';
  if (className) svg = svg.replace('<svg ', `<svg class="${className}" `);
  if (size) svg = svg.replace('<svg ', `<svg width="${size}" height="${size}" `);
  if (strokeWidth) svg = svg.replace(/stroke-width="[^"]*"/, `stroke-width="${strokeWidth}"`);
  return svg;
}
